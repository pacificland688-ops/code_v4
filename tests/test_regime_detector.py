def _make_index_df(
    n_days: int = 250,
    trend: float = 0.0,
    volatility: float = 0.015,
    start_price: float = 100.0,
    start_date: int = 20200101,
    rng_seed: int = 42,
) -> pd.DataFrame:
    """Create synthetic index daily data with realistic sequential dates.

    Dates are generated by skipping weekends (simple heuristic: skip
    dates ending in numbers that look like weekend transitions).
    """
    rng = np.random.default_rng(rng_seed)
    rets = trend + volatility * rng.standard_normal(n_days)
    prices = start_price * np.cumprod(1.0 + rets)
    volumes = rng.lognormal(mean=15.0, sigma=0.5, size=n_days)

    # Generate approximately sequential dates (avoiding weekends naively)
    dates = _generate_sequential_dates(start_date, n_days)

    return pd.DataFrame({
        "ts_code": "000300.SH",
        "trade_date": dates,
        "open": prices * 0.99,
        "high": prices * 1.02,
        "low": prices * 0.98,
        "close": prices,
        "vol": volumes,
    })


def _generate_sequential_dates(start: int, n: int) -> list:
    """Generate n approximately sequential YYYYMMDD dates, skipping weekends."""
    dates = []
    current = start
    while len(dates) < n:
        # Simple check: dates ending in 00-31 are valid-ish
        day = current % 100
        if 1 <= day <= 28:
            dates.append(current)
        current += 1
        # Month rollover
        if (current % 100) > 31:
            current = ((current // 100) * 100) + 101
        if (current // 100) % 100 > 12:
            current = (((current // 10000) + 1) * 10000) + 101
    return sorted(dates)


def _make_prices_df(
    n_stocks: int = 200,
    n_days: int = 250,
    trend: float = 0.0,
    volatility: float = 0.02,
    start_date: int = 20200101,
    rng_seed: int = 42,
) -> pd.DataFrame:
    """Create synthetic stock price data for breadth computation."""
    rng = np.random.default_rng(rng_seed)
    dates = _generate_sequential_dates(start_date, n_days)
    rows = []

    for i in range(n_stocks):
        ts_code = f"{i + 1:06d}.SZ"
        stock_trend = trend + rng.normal(0, 0.0005)
        stock_vol = volatility * (0.5 + rng.random())
        rets = stock_trend + stock_vol * rng.standard_normal(n_days)
        prices = 10.0 * np.cumprod(1.0 + rets)

        for j, d in enumerate(dates):
            rows.append({
                "ts_code": ts_code,
                "trade_date": d,
                "adj_close": prices[j],
            })

    return pd.DataFrame(rows)


def _default_detector_config() -> dict:
    """Return a minimal valid detector config."""
    return {
        "index_code": "000300.SH",
        "trend": {"ma_short": 60, "ma_long": 120, "return_windows": [20, 60, 120]},
        "volatility": {"vol_windows": [20, 60], "drawdown_window": 60},
        "breadth": {"ma_window": 60, "min_stocks": 100},
        "smoothing": {"halflife": 0},  # no smoothing in tests
    }


